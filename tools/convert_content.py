#!/usr/bin/env python3
"""One-shot converter: old Python build output (site_old/) -> Hugo content/ Markdown.

Reads the frozen build's HTML output and writes content/*.md files with front
matter (title/description/date/lastmod/weight/guide_category/type). Article
bodies are extracted byte-identical from <main>; the Hugo template re-injects
the editor byline exactly like build.py did.

Dynamic pages (/hosting/, /offers/, /compare/, /guides/) get front matter only;
their bodies are rendered by Hugo templates/partials from data files.

Idempotent: re-running overwrites content/.
"""
import html
import re
from pathlib import Path
from xml.etree import ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
OLD = ROOT / 'site_old'
CONTENT = ROOT / 'content'

# Pages whose body is rendered by a Hugo template (front matter only).
DYNAMIC = {
    '/hosting/': 'hosting',
    '/offers/': 'offers',
    '/compare/': 'compare',
}
# Section roots handled specially (excluded from guide index entries).
SECTION_ROOTS = {'/ai-tools/', '/guides/', '/ai-news/'}

CATEGORIES = (
    ('writing', 'Writing and checking answers'),
    ('documents', 'Documents, PDFs and tables'),
    ('meetings', 'Meetings and recordings'),
    ('coding', 'Coding and model choices'),
    ('hosting', 'Websites, hosting and costs'),
)


def category(path):
    # Mirrors guide_directory.category().
    if any(w in path for w in ('meeting', 'transcription')):
        return 'meetings'
    if any(w in path for w in ('pdf', 'export', 'zero-blank', 'check-units', 'currency-codes')):
        return 'documents'
    if any(w in path for w in ('cursor', 'copilot', 'coding', 'gemini-flash', 'evaluate-new-ai-model')):
        return 'coding'
    if path.startswith('/guides/') or any(w in path for w in ('hostinger', 'hugging-face', 'ai-app-budget')):
        return 'hosting'
    return 'writing'


def yq(s):
    """Double-quoted YAML scalar."""
    assert '\n' not in s, f'newline in front matter value: {s[:60]!r}'
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def is_index_entry(path):
    return path in ('/start/', '/free-ai/') or (
        any(path.startswith(p) and path != p for p in ('/ai-tools/', '/guides/', '/ai-news/')))


def main():
    xml = ET.parse(OLD / 'sitemap.xml')
    ordered = []
    for u in xml.findall('.//{*}loc'):
        loc = u.text
        assert loc.startswith('https://kikomono.com/')
        ordered.append(loc[len('https://kikomono.com'):])
    lastmods = {}
    for url_el in xml.findall('.//{*}url'):
        loc = url_el.find('{*}loc').text
        lm = url_el.find('{*}lastmod').text
        lastmods[loc[len('https://kikomono.com'):]] = lm

    assert len(ordered) == 45, f'expected 45 pages, got {len(ordered)}'

    for weight, path in enumerate(ordered):
        if path.startswith('/providers/') or path.startswith('/deals/'):
            continue  # generated by tools/prebuild.py
        src = OLD / (path.lstrip('/') + 'index.html') if path != '/' else OLD / 'index.html'
        page_html = src.read_text(encoding='utf-8')
        title = html.unescape(re.search(r'<title>(.*?)</title>', page_html, re.S).group(1))
        desc = html.unescape(re.search(r'<meta name="description" content="([^"]*)">', page_html).group(1))
        lastmod = lastmods[path]

        fm = {'title': title, 'description': desc, 'date': lastmod, 'lastmod': lastmod,
              'weight': weight}
        if is_index_entry(path):
            fm['guide_category'] = category(path)

        body = ''
        if path in DYNAMIC:
            fm['type'] = DYNAMIC[path]
            # Dynamic pages render from Hugo partials; preserve the old
            # <main> trailing-newline count the same way.
            m = re.search(r'<main id="main">(.*?)</main>', page_html, re.S)
            assert m, f'no <main> in {path}'
            dtrail = len(m.group(1)) - len(m.group(1).rstrip('\n'))
            if dtrail:
                fm['trail'] = dtrail
        elif path == '/guides/':
            pass  # section _index, template-driven; front matter only
        else:
            m = re.search(r'<main id="main">(.*?)</main>', page_html, re.S)
            assert m, f'no <main> in {path}'
            body = m.group(1)
            # Intentional content update: point "public repository" links at the
            # live kikomono-hugo repo instead of the retired promo-radar repo.
            body = body.replace('https://github.com/oukiki2026/vps-deals-promo-radar',
                                'https://github.com/oukiki2026/kikomono-hugo')
            # Preserve exact leading/trailing newlines: old templates emit 0-2
            # depending on the page; Goldmark normalizes them away. baseof
            # re-applies via fm['lead']/fm['trail'].
            lead = len(body) - len(body.lstrip('\n'))
            if lead:
                body = body[lead:]
                fm['lead'] = lead
            trail = len(body) - len(body.rstrip('\n'))
            if trail:
                body = body[:len(body) - trail]
                fm['trail'] = trail
            if path.startswith('/ai-tools/free-ai-tools-'):
                # build.py replaced the first </h1> with the byline <p>;
                # restore it here — the Hugo template re-injects identically.
                assert '<p class="byline">By Lika</p>' in body, f'byline missing in {path}'
                body = body.replace('<p class="byline">By Lika</p>', '</h1>', 1)

        # content file location
        if path == '/':
            dest = CONTENT / '_index.md'
        elif path in SECTION_ROOTS:
            dest = CONTENT / path.strip('/') / '_index.md'
        else:
            dest = CONTENT / (path.strip('/') + '.md')
        dest.parent.mkdir(parents=True, exist_ok=True)

        lines = ['---']
        for k, v in fm.items():
            lines.append(f'{k}: {yq(v) if isinstance(v, str) else v}')
        lines.append('---')
        out = '\n'.join(lines) + '\n' + (body + '\n' if body else '')
        dest.write_text(out, encoding='utf-8')
        print(f'{path} -> {dest.relative_to(ROOT)}')

    print(f'done: {len(ordered)} sitemap URLs processed')


if __name__ == '__main__':
    main()
